#!/usr/bin/env python3
"""Readiness report: how far the library is from done, measured from the records.

Reads catalog/weeks, catalog/drafts, catalog/atlas, catalog/path.toml, catalog/use-log.toml,
catalog/concepts.toml and the room-plan index, and writes plans/readiness.md. Run it after
changing any of those (build.py also runs it):

    python3 catalog/readiness.py            # write plans/readiness.md
    python3 catalog/readiness.py --print    # print instead

Each theme sits on the highest rung it reaches on this ladder (see plans/corpus-plan.md):

    library      a week record with a review card (every week has one)
    signed off   organizer-approved or piloted in the catalog
    circle-ready has a room plan in plans/room-plans/
    taught       the use log has a session with it, at home or in the circle

The rungs are counted independently, so a taught theme need not be signed off.
"""
import collections
import pathlib
import re
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAT = ROOT / "catalog"
OUT = ROOT / "plans" / "readiness.md"


def load(path):
    with open(path, "rb") as f:
        return tomllib.load(f)


def week_sort_key(w):
    m = re.match(r"(\d+)(\D*)", w)
    return (int(m.group(1)), m.group(2)) if m else (10**6, w)


def room_plan_weeks():
    """Week ids named in the third column of the room-plan index table."""
    index = ROOT / "plans" / "room-plans" / "README.md"
    weeks = set()
    if not index.exists():
        return weeks
    for line in index.read_text().splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 4 and re.fullmatch(r"\d+e?", cells[2]):
            weeks.add(cells[2])
    return weeks


def theme_rung(record, has_room_plan, has_use):
    """The highest evidenced rung; teaching does not imply organizer sign-off."""
    if has_use:
        return "taught"
    if has_room_plan:
        return "circle-ready"
    if record["status"] in ("organizer-approved", "piloted"):
        return "signed off"
    return "library"


def main(print_report=False):
    concepts = load(CAT / "concepts.toml")
    areas = concepts["areas"]
    cmap = concepts["concepts"]
    weeks = {}
    for f in sorted((CAT / "weeks").glob("*.toml")):
        r = load(f)
        weeks[r["week"]] = r
    drafts = [load(f) for f in sorted((CAT / "drafts").glob("*.toml"))]
    atlas = [load(f) for f in sorted((CAT / "atlas").glob("*.toml"))]
    path = load(CAT / "path.toml")
    uses = load(CAT / "use-log.toml").get("use", [])
    plans = room_plan_weeks()

    def area(rec):
        return cmap[rec["concepts"][0]]["area"]

    taught = collections.defaultdict(set)  # week -> settings
    for u in uses:
        for w in u["weeks"]:
            taught[w].add(u["setting"])
    unknown = sorted(set(taught) - set(weeks), key=week_sort_key)
    if unknown:
        sys.exit(f"use-log.toml names unknown weeks: {', '.join(unknown)}")

    signed = {w for w, r in weeks.items() if r["status"] in ("organizer-approved", "piloted")}
    k1 = {w for w, r in weeks.items() if "K-1" in r["bands"]}
    page_drafts = {w: [d["kind"] for d in r.get("drafts", [])] for w, r in weeks.items() if r.get("drafts")}
    n = len(weeks)

    lines = []
    add = lines.append
    add("# Readiness report")
    add("")
    add("Generated by `python3 catalog/readiness.py` from the catalog records, the six-year path, "
        "the [use log](../catalog/use-log.toml) and the [room-plan index](room-plans/README.md). "
        "Edit those, not this page. What the rungs mean and what counts as done: "
        "[corpus-plan.md](corpus-plan.md).")
    add("")
    add("## Headline")
    add("")
    add("| Rung | Themes | Share of the library |")
    add("|---|---|---|")
    rows = [
        ("Library (pages, guide and review card)", n),
        ("Pages for all three tables (a K–1 entry)", len(k1)),
        ("Signed off (organizer-approved or piloted)", len(signed)),
        ("Circle-ready (a room plan)", len(plans & set(weeks))),
        ("Taught at home or in the circle", len(taught)),
        ("Taught in the circle", sum("circle" in s for s in taught.values())),
    ]
    for label, k in rows:
        add(f"| {label} | {k} | {100 * k / n:.0f}% |")
    add("")
    circle_sessions = sum(u["setting"] == "circle" for u in uses)
    home_sessions = sum(u["setting"] == "home" for u in uses)
    add(f"The use log has {circle_sessions} circle sessions and {home_sessions} home sessions. "
        f"Awaiting the organizer's review: {len(drafts)} new-theme drafts and "
        f"{len(page_drafts)} weeks with drafted pages "
        f"({sum(k.count('return visit') for k in page_drafts.values())} return visits, "
        f"{sum(k.count('K-1 pages') for k in page_drafts.values())} sets of K–1 pages). "
        f"The atlas adds {len(atlas)} investigation families, "
        f"{sum(bool(a['bands']) for a in atlas)} of them with a K–5 entry.")
    add("")

    add("## By area")
    add("")
    add("| Area | Themes | K–1 entry | 4–5 only | Signed off | Room plan | Taught | Draft themes waiting | Atlas families |")
    add("|---|---|---|---|---|---|---|---|---|")
    for aid, aname in areas.items():
        ws = [w for w, r in weeks.items() if area(r) == aid]
        add("| {} | {} | {} | {} | {} | {} | {} | {} | {} |".format(
            aname, len(ws), sum(w in k1 for w in ws),
            sum(weeks[w]["bands"] == ["4-5"] for w in ws),
            sum(w in signed for w in ws), sum(w in plans for w in ws),
            sum(w in taught for w in ws),
            sum(area(d) == aid for d in drafts),
            sum(area(a) == aid for a in atlas)))
    add("")

    add("## The six-year path")
    add("")
    add("The [path](six-year-path.md) is a proposal. A session is one hour. The last four "
        "columns count weekly-theme sessions only, not return visits or atlas families.")
    add("")
    add("| Year | Hours | Sessions | Weekly-theme sessions with K–1 pages | Signed off | Room plan | Taught |")
    add("|---|---|---|---|---|---|---|")
    by_year = collections.defaultdict(list)
    for s in path["session"]:
        by_year[s["year"]].append(s)
    for y in sorted(by_year):
        ss = by_year[y]
        direct = [s["id"] for s in ss if s["id"] in weeks]
        add("| {} | {} | {} | {} of {} | {} | {} | {} |".format(
            y, sum(s.get("hours", 1) for s in ss), len(ss),
            sum(w in k1 for w in direct), len(direct),
            sum(w in signed for w in direct), sum(w in plans for w in direct),
            sum(w in taught for w in direct)))
    add("")

    add("## Taught so far")
    add("")
    add("| Date | Setting | Weeks | Activity | Outcome |")
    add("|---|---|---|---|---|")
    for u in sorted(uses, key=lambda u: u["date"]):
        ws = ", ".join(f"{w} {weeks[w]['title']}" for w in u["weeks"]) or "none named"
        add(f"| {u['date']} | {u['setting']} | {ws} | {u['activity']} | {u['outcome']} |")
    add("")

    text = "\n".join(lines) + "\n"
    if print_report:
        print(text, end="")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main(print_report="--print" in sys.argv)
