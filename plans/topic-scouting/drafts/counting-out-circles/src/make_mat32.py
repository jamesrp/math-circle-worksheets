"""Write mat32-left.tex and mat32-right.tex: a 32-spot loop that spans two
US Letter pages laid side by side (left page, right page).

Coordinates are in cm relative to the lower-left corner of the text area
(text width 18.59 cm, text height 23.84 cm; 1.5 cm side margins). Spots are
2.6 cm across, for 1-inch counters. The loop is a rounded rectangle; the left
page holds its left half and the right page is the mirror image. Numbers run
clockwise from spot 1 at the top left. The guide line runs off the inner
edge of each page so that the two halves visibly join.
"""
import math

TW, TH = 18.59, 23.84       # text area
SIDE = 1.5                  # side margin
SPOT_R = 1.3
LABEL_OFF = SPOT_R + 0.62   # spot centre to label centre
YT = TH - 2.25              # top run
YB = 2.25                   # bottom run
XL = 2.4                    # outer side
XE = TW + SIDE - 0.8 - SPOT_R   # inner end: spot edge 0.8 cm from paper edge
RC = 3.0                    # corner radius
N_PAGE = 16


def path_point(s):
    """Point and outward normal at arc length s along the left-page path,
    which runs from the bottom inner end, left along the bottom, up the
    outer side and right along the top to the top inner end."""
    bottom = XE - (XL + RC)
    side = (YT - RC) - (YB + RC)
    arc = math.pi / 2 * RC
    # bottom straight, leftwards
    if s <= bottom:
        return (XE - s, YB), (0, -1)
    s -= bottom
    if s <= arc:   # lower-left corner, centre (XL+RC, YB+RC)
        a = -math.pi / 2 - s / RC
        cx, cy = XL + RC, YB + RC
        return (cx + RC * math.cos(a), cy + RC * math.sin(a)), (math.cos(a), math.sin(a))
    s -= arc
    if s <= side:
        return (XL, YB + RC + s), (-1, 0)
    s -= side
    if s <= arc:   # upper-left corner, centre (XL+RC, YT-RC)
        a = math.pi - s / RC
        cx, cy = XL + RC, YT - RC
        return (cx + RC * math.cos(a), cy + RC * math.sin(a)), (math.cos(a), math.sin(a))
    s -= arc
    return (XL + RC + s, YT), (0, 1)


def total_length():
    return 2 * (XE - (XL + RC)) + ((YT - RC) - (YB + RC)) + math.pi * RC


def spots_left():
    L = total_length()
    step = L / (N_PAGE - 1)
    return [path_point(i * step) for i in range(N_PAGE)], step


def numbering():
    """Clockwise order around the joined loop: left page L0..L15 (bottom
    inner end round to top inner end), then right page R0..R15 (top inner
    end round to bottom inner end). Spot 1 is the first spot on the left
    page's top run."""
    pts, _ = spots_left()
    first_top = next(i for i, ((x, y), n) in enumerate(pts) if n == (0, 1) or (y > YT - 0.05))
    cycle = [("L", i) for i in range(N_PAGE)] + [("R", i) for i in range(N_PAGE)]
    start = cycle.index(("L", first_top))
    num = {}
    for k in range(len(cycle)):
        num[cycle[(start + k) % len(cycle)]] = k + 1
    return num


def emit(page):
    pts, step = spots_left()
    num = numbering()
    out = []
    out.append("% generated by make_mat32.py; do not edit by hand")
    out.append(r"\begin{tikzpicture}[x=1cm,y=1cm]")
    # bounding box a little shorter than the text area, so the picture fits
    # on one page; the top and bottom numbers sit just outside it
    out.append(r"\useasboundingbox (0,0.30) rectangle (%.2f,%.2f);" % (TW, TH - 0.30))

    def X(x):
        return x if page == "L" else TW - x

    # guide line: from beyond the inner paper edge, round the corners, back out
    far = TW + SIDE + 1.0     # past the paper edge on the left page
    p = []
    p.append("(%.3f,%.3f)" % (X(far), YB))
    p.append("(%.3f,%.3f)" % (X(XL + RC), YB))
    if page == "L":
        p.append("arc[start angle=270, end angle=180, radius=%.2f]" % RC)
    else:
        p.append("arc[start angle=270, end angle=360, radius=%.2f]" % RC)
    p.append("-- (%.3f,%.3f)" % (X(XL), YT - RC))
    if page == "L":
        p.append("arc[start angle=180, end angle=90, radius=%.2f]" % RC)
    else:
        p.append("arc[start angle=0, end angle=90, radius=%.2f]" % RC)
    p.append("-- (%.3f,%.3f)" % (X(far), YT))
    out.append(r"\draw[ringline, line width=0.8pt] %s -- %s %s %s %s %s;" % (
        p[0], p[1], p[2], p[3], p[4], p[5]))
    for i, ((x, y), (nx, ny)) in enumerate(pts):
        if page == "R":
            idx = ("R", N_PAGE - 1 - i)
        else:
            idx = ("L", i)
        n = num[idx]
        out.append(r"\filldraw[fill=white, draw=black, line width=1pt] (%.3f,%.3f) circle (%.2f);"
                   % (X(x), y, SPOT_R))
        lx, ly = x + LABEL_OFF * nx, y + LABEL_OFF * ny
        out.append(r"\node[font=\large\bfseries, inner sep=0pt] at (%.3f,%.3f) {%d};"
                   % (X(lx), ly, n))
    label = ("Mat with 32 spots, left half. Lay the right half beside it." if page == "L"
             else "Mat with 32 spots, right half.")
    out.append(r"\node[align=center, text width=7cm] at (%.3f,%.3f) {%s};" % (TW / 2, (YB + YT) / 2, label))
    out.append(r"\end{tikzpicture}")
    return "\n".join(out) + "\n", step


if __name__ == "__main__":
    for page, fn in (("L", "mat32-left.tex"), ("R", "mat32-right.tex")):
        text, step = emit(page)
        with open(fn, "w") as f:
            f.write(text)
    pts, step = spots_left()
    # check spacing between neighbouring spot centres on one page
    d = [math.dist(pts[i][0], pts[i + 1][0]) for i in range(N_PAGE - 1)]
    join = 2 * (TW + SIDE - XE)
    print("path step %.2f cm, min centre gap %.2f cm (spot 2.6 cm), join gap %.2f cm"
          % (step, min(d), join))
    num = numbering()
    print("left page numbers:", [num[("L", i)] for i in range(N_PAGE)])
    print("right page numbers:", [num[("R", i)] for i in range(N_PAGE)])
