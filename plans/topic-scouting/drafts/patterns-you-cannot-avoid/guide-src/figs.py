"""Write figures.tex: the TikZ pictures used in facilitator.tex.

Run: python3 figs.py   (build.sh runs it before pdflatex)
"""
import math


def f(x):
    return f'{x:.3f}'


def counter(cx, cy, s, c):
    col = {'R': 'cred', 'B': 'cblue'}[c]
    return (rf'\fill[{col}] ({f(cx)},{f(cy)}) circle ({f(0.36 * s)});'
            rf'\node[text=white,font=\bfseries\tiny] at ({f(cx)},{f(cy)}) {{{c}}};')


def strip(colours, s, x0=0.0, y0=0.0, comb=None):
    """A numbered strip with counters; comb = (first, gap) lays a comb card with three windows on it."""
    n = len(colours)
    out = []
    for i in range(1, n + 1):
        x = x0 + (i - 1) * s
        out.append(rf'\draw[line width=0.7pt] ({f(x)},{f(y0)}) rectangle ({f(x + s)},{f(y0 + s)});')
        out.append(rf'\node[font=\scriptsize, anchor=base] at ({f(x + s / 2)},{f(y0 - 0.32)}) {{{i}}};')
        out.append(counter(x + s / 2, y0 + s / 2, s, colours[i - 1]))
    if comb:
        # drawn like Materials page 1: notches open downward, tooth ends on the strip's bottom edge,
        # 23 of 25 mm windows, the spine reaching 9 mm above the strip; Comb 1's windows join into one notch
        first, gap = comb
        wins = [first, first + gap, first + 2 * gap]
        spans = [(wins[0], wins[2])] if gap == 1 else [(w, w) for w in wins]
        left = x0 + (wins[0] - 1) * s - 0.24 * s
        right = x0 + wins[2] * s + 0.24 * s
        bot, ntop, top = y0, y0 + s * 27 / 25, y0 + s * 34 / 25
        pts = [(left, bot)]
        for a, b in spans:
            xa, xb = x0 + (a - 1) * s + 0.04 * s, x0 + b * s - 0.04 * s
            pts += [(xa, bot), (xa, ntop), (xb, ntop), (xb, bot)]
        pts += [(right, bot), (right, top), (left, top)]
        path = ' -- '.join(f'({f(x)},{f(y)})' for x, y in pts) + ' -- cycle'
        out.append(rf'\filldraw[fill=gray!55, line width=0.6pt] {path};')
    return '\n'.join(out)


def launch():
    """One possible launch run on the 5-square strip (review M1: no alternating first try)."""
    s = 0.62
    panels = [('RRBBB', (3, 1), r'Comb 1 at 3, 4, 5\\shows three blues', r'\ding{55}', '1. First try'),
              ('RRRBB', (1, 1), r'Comb 1 at 1, 2, 3\\now shows three reds', r'\ding{55}', '2. Change square 3'),
              ('RRBRR', None, r'Combs 1 and 2 in every\\place: all mixed', r'\ding{51}', '3. A good strip')]
    out = []
    for k, (cols, comb, cap, mark, lab) in enumerate(panels):
        x0 = k * 5.9
        out.append(strip(cols, s, x0, 0, comb))
        out.append(rf'\node[font=\large] at ({f(x0 + 5 * s + 0.45)},{f(s / 2)}) {{{mark}}};')
        out.append(rf'\node[font=\footnotesize, text width=4.6cm, align=flush center, anchor=north] at '
                   rf'({f(x0 + 2.5 * s)},-0.55) {{{cap}}};')
        out.append(rf'\node[font=\footnotesize\bfseries, anchor=south] at ({f(x0 + 2.5 * s)},{f(s + 0.15)}) {{{lab}}};')
    return r'\begin{tikzpicture}' + '\n'.join(out) + r'\end{tikzpicture}'


def dots_fig(n, diam, red, blue_dashed=True, label=None, width=3.4):
    r = diam / 2
    pts = [(r * math.cos(math.pi / 2 + 2 * math.pi * k / n), r * math.sin(math.pi / 2 + 2 * math.pi * k / n))
           for k in range(n)]
    out = []
    for i in range(n):
        for j in range(i + 1, n):
            e = (i, j)
            if e in red:
                out.append(rf'\draw[cred, line width=1.6pt] ({f(pts[i][0])},{f(pts[i][1])}) -- ({f(pts[j][0])},{f(pts[j][1])});')
            else:
                out.append(rf'\draw[cblue, line width=0.9pt, dash pattern=on 2.2pt off 1.4pt] ({f(pts[i][0])},{f(pts[i][1])}) -- ({f(pts[j][0])},{f(pts[j][1])});')
    for x, y in pts:
        out.append(rf'\fill ({f(x)},{f(y)}) circle (0.07);')
    if label:
        out.append(rf'\node[font=\scriptsize, anchor=north, text width={width}cm, align=center] at (0,{f(-r - 0.12)}) {{{label}}};')
    return r'\begin{tikzpicture}[baseline=(current bounding box.north)]' + '\n'.join(out) + r'\end{tikzpicture}'


def five_types():
    pent = {(0, 1), (1, 2), (2, 3), (3, 4), (0, 4)}
    bent = {(0, 1), (1, 2), (3, 4), (2, 4), (0, 3)}
    return (dots_fig(5, 1.9, pent, label='loop and star: 1, and its swap', width=2.4)
            + r'\hspace{0.3cm}' +
            dots_fig(5, 1.9, bent, label='bent loops: 5 turns, and their swaps', width=2.4))


def six_two():
    red = {(0, 2), (2, 4), (0, 4), (1, 3), (3, 5), (1, 5)}
    return dots_fig(6, 2.1, red, label='exactly two one-colour triangles')


if __name__ == '__main__':
    with open('figures.tex', 'w') as fh:
        fh.write('% generated by figs.py\n')
        fh.write(r'\newcommand{\launchfig}{' + launch() + '}\n')
        fh.write(r'\newcommand{\fivefig}{' + five_types() + '}\n')
        fh.write(r'\newcommand{\sixfig}{' + six_two() + '}\n')
    print('wrote figures.tex')
